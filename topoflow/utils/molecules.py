"""Create RDKit molecules from atom positions and types using Open Babel."""

import tempfile
import numpy as np
from rdkit import Chem, RDLogger
from openbabel import openbabel
from tqdm import tqdm
import torch

openbabel.cvar.obErrorLog.StopLogging()


def make_mol_openbabel(positions, atom_types, atom_decoder):
    """Build an RDKit molecule using openbabel for creating bonds.

    Args:
        positions: N x 3 (e.g., numpy array or list of lists) - 3D coordinates of N atoms.
        atom_types: N (e.g., list of integers) - Indices representing atom types.
        atom_decoder: A dictionary or list that maps atom_types indices to their chemical symbols
                      (e.g., {0: 'C', 1: 'O'}).

    Returns:
        rdkit molecule (Chem.Mol object)
    """
    if not isinstance(atom_types, list) and atom_types.ndim == 2:
        atoms_idxs = torch.argmax(atom_types, dim=1).cpu().numpy()
    elif isinstance(atom_types, list) or atom_types.ndim == 1:
        atoms_idxs = atom_types

    atom_symbols = [atom_decoder[x] for x in atoms_idxs]

    num_atoms = len(positions)
    xyz_lines = [str(num_atoms), "Generated by make_mol_openbabel"]
    for i in range(num_atoms):
        xyz_lines.append(
            f"{atom_symbols[i]} {positions[i][0]:.6f} {positions[i][1]:.6f} {positions[i][2]:.6f}"
        )
    xyz_string = "\n".join(xyz_lines)

    obConversion = openbabel.OBConversion()
    obConversion.SetInAndOutFormats("xyz", "sdf")
    ob_mol = openbabel.OBMol()

    obConversion.ReadString(ob_mol, xyz_string)

    sdf_string = obConversion.WriteString(ob_mol)

    tmp_mol = Chem.MolFromMolBlock(sdf_string, sanitize=False)

    if tmp_mol is None:
        print("Failed to create RDKit molecule from Open Babel SDF string.")
        return None

    # Build new molecule. This is a workaround to remove radicals.
    mol = Chem.RWMol()
    for atom in tmp_mol.GetAtoms():
        mol.AddAtom(Chem.Atom(atom.GetSymbol()))
    mol.AddConformer(tmp_mol.GetConformer(0))

    for bond in tmp_mol.GetBonds():
        mol.AddBond(bond.GetBeginAtomIdx(), bond.GetEndAtomIdx(), bond.GetBondType())

    return mol


def mol_to_data(mol, atom_encoder, batch_id=0):
    """Convert an RDKit molecule to a PyTorch Geometric Data object."""
    # --- 3D coordinates ---
    conf = mol.GetConformer()
    coords = torch.tensor(
        conf.GetPositions(), dtype=torch.float
    )  # shape: [num_atoms, 3]

    # --- Atom types one-hot ---
    atom_types = [atom_encoder[atom.GetSymbol()] for atom in mol.GetAtoms()]
    num_atom_types = max(atom_encoder.values()) + 1
    atom_types_tensor = torch.tensor(atom_types, dtype=torch.long)
    one_hot = torch.nn.functional.one_hot(
        atom_types_tensor, num_classes=num_atom_types
    ).float()  # shape: [num_atoms, num_atom_types]

    # --- Batch ---
    batch = torch.full((coords.size(0),), batch_id, dtype=torch.long)

    return coords, one_hot, batch


def data_to_rdmol(
    data, atom_decoder, sanitize=False, show_progress=False, verbose=True
):
    """Convert PyTorch Geometric Data object to RDKit molecule."""
    rdkit_logger = RDLogger.logger()
    rdkit_logger.setLevel(RDLogger.CRITICAL)

    coords = data["x_lig"].to("cpu")
    atom_types = data["h_lig"].to("cpu")
    batch = data["batch_lig"].to("cpu")
    batch = batch[batch != -1]  # Remove -1 entries

    # Convert atom types from one-hot to indices
    atom_idxs = torch.argmax(atom_types, dim=1).cpu().numpy()

    unique_batches = torch.unique(batch)

    rd_mols = []
    if show_progress:
        unique_batches = tqdm(unique_batches, desc="Converting data to RDKit molecules")
    for batch_id in unique_batches:
        coords_batch = coords[batch == batch_id]
        atom_idxs_batch = atom_idxs[batch == batch_id]
        rdmol = make_mol_openbabel(coords_batch.numpy(), atom_idxs_batch, atom_decoder)
        if rdmol is not None:
            if sanitize:
                try:
                    Chem.SanitizeMol(rdmol)
                except Exception as e:
                    if verbose:
                        print(f"Sanitization failed for batch {batch_id}: {e}")
                    rd_mols.append(None)
                    continue
            rd_mols.append(rdmol)

    return rd_mols


def rdmol_to_smiles(rdmol):
    """Convert RDKit molecule to SMILES string."""
    try:
        mol = Chem.Mol(rdmol)
        Chem.RemoveStereochemistry(mol)
        mol = Chem.RemoveHs(mol)
        return Chem.MolToSmiles(mol)
    except Exception as e:
        print(f"Error converting RDKit molecule to SMILES: {e}")
        return None
