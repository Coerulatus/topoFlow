def make_mol_openbabel(positions, atom_types, atom_decoder):
    """Build an RDKit molecule using openbabel for creating bonds.

    Args:
        positions: N x 3 (e.g., numpy array or list of lists) - 3D coordinates of N atoms.
        atom_types: N (e.g., list of integers) - Indices representing atom types.
        atom_decoder: A dictionary or list that maps atom_types indices to their chemical symbols
                      (e.g., {0: 'C', 1: 'O'}).

    Returns:
        rdkit molecule (Chem.Mol object)
    """
    if not isinstance(atom_types, list) and atom_types.ndim == 2:
        atoms_idxs = torch.argmax(atom_types, dim=1).cpu().numpy()
    elif isinstance(atom_types, list) or atom_types.ndim == 1:
        atoms_idxs = atom_types

    atom_symbols = [atom_decoder[x] for x in atoms_idxs]

    num_atoms = len(positions)
    xyz_lines = [str(num_atoms), "Generated by make_mol_openbabel"]
    for i in range(num_atoms):
        xyz_lines.append(
            f"{atom_symbols[i]} {positions[i][0]:.6f} {positions[i][1]:.6f} {positions[i][2]:.6f}"
        )
    xyz_string = "\n".join(xyz_lines)

    obConversion = openbabel.OBConversion()
    obConversion.SetInAndOutFormats("xyz", "sdf")
    ob_mol = openbabel.OBMol()

    obConversion.ReadString(ob_mol, xyz_string)

    sdf_string = obConversion.WriteString(ob_mol)

    tmp_mol = Chem.MolFromMolBlock(sdf_string, sanitize=False)

    if tmp_mol is None:
        print("Failed to create RDKit molecule from Open Babel SDF string.")
        return None

    # Build new molecule. This is a workaround to remove radicals.
    mol = Chem.RWMol()
    for atom in tmp_mol.GetAtoms():
        mol.AddAtom(Chem.Atom(atom.GetSymbol()))
    mol.AddConformer(tmp_mol.GetConformer(0))

    for bond in tmp_mol.GetBonds():
        mol.AddBond(bond.GetBeginAtomIdx(), bond.GetEndAtomIdx(), bond.GetBondType())

    return mol


def make_mol_openbabel_with_bonds(
    positions, atom_types, atom_decoder, explicit_bonds=None
):
    """Build an RDKit molecule using openbabel, allowing for manual bond overrides.

    Args:
        positions: N x 3 coordinates.
        atom_types: N indices or one-hot vectors.
        atom_decoder: Dict mapping indices to symbols (e.g., {0: 'C'}).
        explicit_bonds: (Optional) List of tuples (atom_idx1, atom_idx2, bond_type).
                        Example: [(0, 1, Chem.BondType.SINGLE), (5, 6, Chem.BondType.AROMATIC)]
                        These bonds take precedence over Open Babel's guesses.

    Returns:
        rdkit molecule (Chem.Mol object)
    """
    # --- 1. Standard Input Processing ---
    if (
        not isinstance(atom_types, list)
        and hasattr(atom_types, "ndim")
        and atom_types.ndim == 2
    ):
        atoms_idxs = torch.argmax(atom_types, dim=1).cpu().numpy()
    elif isinstance(atom_types, list) or (
        hasattr(atom_types, "ndim") and atom_types.ndim == 1
    ):
        atoms_idxs = atom_types

    atom_symbols = [atom_decoder[x] for x in atoms_idxs]
    num_atoms = len(positions)

    # --- 2. Open Babel Geometry Parsing ---
    # We still use OB to generate the initial connectivity guess based on 3D distances
    xyz_lines = [str(num_atoms), "Generated by make_mol_openbabel"]
    for i in range(num_atoms):
        xyz_lines.append(
            f"{atom_symbols[i]} {positions[i][0]:.6f} {positions[i][1]:.6f} {positions[i][2]:.6f}"
        )
    xyz_string = "\n".join(xyz_lines)

    obConversion = openbabel.OBConversion()
    obConversion.SetInAndOutFormats("xyz", "sdf")
    ob_mol = openbabel.OBMol()
    obConversion.ReadString(ob_mol, xyz_string)  # Open Babel calculates bonds here
    sdf_string = obConversion.WriteString(ob_mol)

    # Create the temporary RDKit mol from the OB output
    tmp_mol = Chem.MolFromMolBlock(sdf_string, sanitize=False)

    if tmp_mol is None:
        print("Failed to create RDKit molecule from Open Babel SDF string.")
        return None

    # --- 3. Build New Molecule (Merging logic) ---
    mol = Chem.RWMol()

    # A. Add Atoms
    for atom in tmp_mol.GetAtoms():
        mol.AddAtom(Chem.Atom(atom.GetSymbol()))

    # B. Add Explicit (User-Defined) Bonds FIRST
    # We use a set to keep track of pairs we have manually handled
    handled_pairs = set()

    if explicit_bonds:
        for idx1, idx2, bond_type in explicit_bonds:
            # RDKit indices must be int
            idx1, idx2 = int(idx1), int(idx2)

            if mol.GetBondBetweenAtoms(idx1, idx2) is None:
                mol.AddBond(idx1, idx2, bond_type)

            # Store sorted pair so order (0,1) matches (1,0)
            pair = tuple(sorted((idx1, idx2)))
            handled_pairs.add(pair)

    # C. Add Open Babel Bonds (The "Rest")
    # Only add if we haven't already added a bond there manually
    for bond in tmp_mol.GetBonds():
        idx1 = bond.GetBeginAtomIdx()
        idx2 = bond.GetEndAtomIdx()

        pair = tuple(sorted((idx1, idx2)))

        # If we haven't manually defined this connection, accept Open Babel's guess
        if pair not in handled_pairs:
            # Note: You might want to map OB bond types to RDKit types if needed,
            # but usually getting the type from the tmp_mol works fine.
            mol.AddBond(idx1, idx2, bond.GetBondType())

    # D. Add Conformer (Geometry)
    mol.AddConformer(tmp_mol.GetConformer(0))

    # Optional: Sanitize to recalculate valence/aromaticity based on the new graph
    # Chem.SanitizeMol(mol)

    return mol.GetMol()


def extract_bonds(mol):
    """Extracts bonds from an RDKit molecule.

    Needed for manual overrides in the make_mol_openbabel function.

    Args:
        mol: RDKit molecule (Chem.Mol)

    Returns:
        List of tuples: [(atom_idx1, atom_idx2, Chem.BondType), ...]
    """
    explicit_bonds = []

    # Iterate over all bonds in the molecule
    for bond in mol.GetBonds():
        # Get the indices of the two atoms involved
        i = bond.GetBeginAtomIdx()
        j = bond.GetEndAtomIdx()

        # Get the specific bond type (SINGLE, DOUBLE, AROMATIC, etc.)
        b_type = bond.GetBondType()

        # Sort indices so that the smaller index is always first.
        # This creates a canonical representation (e.g., always (0, 1), never (1, 0))
        idx1 = min(i, j)
        idx2 = max(i, j)

        explicit_bonds.append((idx1, idx2, b_type))

    return explicit_bonds


def mol_to_data(mol, atom_encoder, batch_id=0):
    """Convert an RDKit molecule to a PyTorch Geometric Data object."""
    # --- 3D coordinates ---
    conf = mol.GetConformer()
    coords = torch.tensor(
        conf.GetPositions(), dtype=torch.float
    )  # shape: [num_atoms, 3]

    # --- Atom types one-hot ---
    atom_types = [atom_encoder[atom.GetSymbol()] for atom in mol.GetAtoms()]
    num_atom_types = max(atom_encoder.values()) + 1
    atom_types_tensor = torch.tensor(atom_types, dtype=torch.long)
    one_hot = torch.nn.functional.one_hot(
        atom_types_tensor, num_classes=num_atom_types
    ).float()  # shape: [num_atoms, num_atom_types]

    # --- Batch ---
    batch = torch.full((coords.size(0),), batch_id, dtype=torch.long)

    return coords, one_hot, batch


def data_to_rdmol(
    data, atom_decoder, sanitize=False, show_progress=False, verbose=True
):
    """Convert PyTorch Geometric Data object to RDKit molecule."""
    rdkit_logger = RDLogger.logger()
    rdkit_logger.setLevel(RDLogger.CRITICAL)

    coords = data["x_lig"].to("cpu")
    atom_types = data["h_lig"].to("cpu")
    batch = data["batch_lig"].to("cpu")
    batch = batch[batch != -1]  # Remove -1 entries

    # Convert atom types from one-hot to indices
    atom_idxs = torch.argmax(atom_types, dim=1).cpu().numpy()

    unique_batches = torch.unique(batch)

    rd_mols = []
    if show_progress:
        unique_batches = tqdm(unique_batches, desc="Converting data to RDKit molecules")
    for batch_id in unique_batches:
        coords_batch = coords[batch == batch_id]
        atom_idxs_batch = atom_idxs[batch == batch_id]
        rdmol = make_mol_openbabel(coords_batch.numpy(), atom_idxs_batch, atom_decoder)
        if rdmol is not None:
            if sanitize:
                try:
                    Chem.SanitizeMol(rdmol)
                except Exception as e:
                    if verbose:
                        print(f"Sanitization failed for batch {batch_id}: {e}")
                    rd_mols.append(None)
                    continue
            rd_mols.append(rdmol)

    return rd_mols


def rdmol_to_smiles(rdmol):
    """Convert RDKit molecule to SMILES string."""
    try:
        mol = Chem.Mol(rdmol)
        Chem.RemoveStereochemistry(mol)
        mol = Chem.RemoveHs(mol)
        return Chem.MolToSmiles(mol)
    except Exception as e:
        print(f"Error converting RDKit molecule to SMILES: {e}")
        return None


def pdb_to_data_object(
    pdb_file: str,
    atom_encoder: dict,
    save_path: str = None,
    normalization_path: str = None,
    remove_hydrogens: bool = True,
    center_pocket: bool = True,
    only_coords: bool = False,
    verbose: bool = False,
    force: bool = False,
) -> Data:
    """Reads a PDB file using RDKit and creates a PyTorch Geometric Data object for pocket atoms.

    This function uses RDKit's PDB parser to load the structure, then extracts coordinates
    and converts atomic element symbols into a one-hot feature matrix using the provided
    atom_encoder. It checks for and saves to a cache file for optimization.

    Args:
        pdb_file (str): Path to the input PDB file (e.g., a protein pocket file).
        atom_encoder (dict): Dictionary mapping atomic element symbols (e.g., 'C', 'N')
                             to their corresponding index (int) used in the one-hot encoding.
        save_path (str, optional): Path to save/load the resulting Data object (e.g., 'pocket_cache.pt').
                                   If the file exists, it is loaded; otherwise, the parsed data is saved here.
                                   Defaults to None (no caching).
        normalization_path (str, optional): Path to normalization parameters file.
        remove_hydrogens (bool): If True, all hydrogen atoms are removed from the molecule
                                 after loading and before featurization. Defaults to True.
        center_pocket (bool): If True, centers the pocket coordinates to the origin. Defaults to True.
        only_coords (bool): If True, returns a feature tensor (h_pocket) containing only zeros.
                            Defaults to False.
        verbose (bool): If True, prints status updates and parsing details.
        force (bool): If True, forces re-parsing and ignores any cached file at save_path. Defaults to False.

    Returns:
        Data: A PyTorch Geometric Data object containing:
            - `x_pocket`: Coordinates (N_pocket x 3)
            - `h_pocket`: One-hot features (N_pocket x D_features)
            - `batch_pocket`: Batch index (constant 0 for a single file)
    """
    if save_path is not None and os.path.exists(save_path) and not force:
        if verbose:
            print(f"Loading pocket data from cache: {save_path}")
        with torch.serialization.safe_globals(
            [
                torch_geometric.data.Data,
                torch_geometric.data.data.DataEdgeAttr,
                torch_geometric.data.data.DataTensorAttr,
                torch_geometric.data.storage.GlobalStorage,
            ]
        ):
            pocket = torch.load(save_path, weights_only=True)
    try:
        # Load the molecule, sanitize=False is critical for protein structures
        # We use removeHs=False here because we will handle hydrogen removal explicitly below
        mol = Chem.MolFromPDBFile(pdb_file, sanitize=False, removeHs=False)
        if mol is None:
            raise ValueError("RDKit could not parse the PDB file.")
    except Exception as e:
        raise RuntimeError(f"Failed to read PDB file with RDKit: {e}")

    # --- Hydrogen Removal Logic ---
    if remove_hydrogens:
        if verbose:
            print("Removing hydrogen atoms from the pocket molecule...")
        # Use Chem.RemoveHs to create a new molecule object without Hydrogens
        mol = Chem.RemoveHs(mol)
    # --- End Hydrogen Removal Logic ---

    # Use the existing mol_to_data function to get coordinates and features.
    # We pass batch_id=0 as a single PDB file represents one pocket.
    coords, one_hot_features, batch_index = mol_to_data(mol, atom_encoder, batch_id=0)

    num_atoms = coords.shape[0]
    num_features = one_hot_features.shape[1]

    # Apply 'only_coords' logic to set features to zero if necessary
    if only_coords:
        h_pocket = torch.zeros((num_atoms, num_features), dtype=torch.float32)
    else:
        h_pocket = one_hot_features

    if normalization_path is not None:
        if verbose:
            print(f"Applying normalization from: {normalization_path}")
        norm_params = np.load(normalization_path, allow_pickle=True)
        mean = norm_params["mean"]
        std = norm_params["std"]
        coords = (coords - torch.tensor(mean, dtype=torch.float32)) / torch.tensor(
            std, dtype=torch.float32
        )

    if center_pocket:
        if verbose:
            print("Centering pocket coordinates to the origin...")
        centroid = coords.mean(dim=0, keepdim=True)
        coords = coords - centroid
    # Rename tensors for the pocket Data object
    pocket_data = Data(
        x_pocket=coords,
        h_pocket=h_pocket,
        # Use the batch index tensor, renaming to pocket context
        batch_pocket=batch_index,
    )

    if save_path is not None:
        os.makedirs(os.path.dirname(save_path) or ".", exist_ok=True)
        torch.save(pocket_data, save_path)
        if verbose:
            print(f"Parsed data saved to cache: {save_path}")

    if verbose:
        print(f"Successfully parsed {num_atoms} pocket atoms using RDKit.")

    return pocket_data


def get_largest_fragment_info(mol: Chem.Mol):
    """Finds the largest connected fragment in an RDKit molecule.

    Returns:
        tuple: (largest_fragment_mol, largest_fragment_size)
    """
    if mol is None:
        return None, 0

    # Get fragments as atom indices, then convert to RDKit molecules
    try:
        frags = Chem.GetMolFrags(mol, asMols=True)

        largest_fragment = None
        max_size = 0

        for fragment in frags:
            size = fragment.GetNumAtoms()
            if size > max_size:
                max_size = size
                largest_fragment = fragment

        return largest_fragment, max_size
    except Exception as e:
        print(f"Error in getting largest fragment: {e}")
        return None, 0


def load_sdf_molecules_rdkit(file_path):
    """Loads molecules from an SDF file using RDKit's SDMolSupplier.

    Args:
        file_path (str): The path to the SDF file.

    Returns:
        list: A list of RDKit molecule objects (Chem.Mol).
    """
    try:
        # Create an SDMolSupplier object
        supplier = Chem.SDMolSupplier(file_path)

        # Iterate through the supplier to get the molecules
        molecules = [mol for mol in supplier if mol is not None]

        return molecules
    except Exception as e:
        print(f"An error occurred: {e}")
        return []


def data_to_list(data):
    """Split a batched PyTorch Geometric Data object into a list of individual Data objects."""
    batch_lig = data["batch_lig"]
    batch_lig = batch_lig[batch_lig != -1]  # Remove -1 entries
    batch_pocket = data["batch_pocket"]
    batch_pocket = batch_pocket[batch_pocket != -1]  # Remove -1 entries
    unique_batches = torch.unique(torch.cat([batch_lig, batch_pocket]))

    data_list = []
    for batch_id in unique_batches:
        if batch_id != -1:
            mask_lig = batch_lig == batch_id
            mask_pocket = batch_pocket == batch_id

            data_item = Data(
                x_lig=data["x_lig"][mask_lig],
                h_lig=data["h_lig"][mask_lig],
                batch_lig=torch.zeros(mask_lig.sum(), dtype=torch.long),
                x_pocket=data["x_pocket"][mask_pocket],
                h_pocket=data["h_pocket"][mask_pocket],
                batch_pocket=torch.zeros(mask_pocket.sum(), dtype=torch.long),
            )
            data_list.append(data_item)
    return data_list
